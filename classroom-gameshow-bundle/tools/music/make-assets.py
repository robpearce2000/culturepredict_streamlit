#!/usr/bin/env python3
"""
Builds the launcher music that ships inside the single HTML file (draft B, chosen by Rob):
  python3 tools/music/make-assets.py   ->  src/shared/music-data.js  (base64 MP3 loop and fanfare)
The loop is cut at exact bar lines from the middle of three rendered passes (see loop.py), so it repeats
with no gap; the MP3 carries its gapless delay/padding (LAME header), which browsers honour when decoding.
"""
import base64, os, subprocess, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import loop

ROOT = loop.ROOT
CHOSEN = 'b'
BITRATE = os.environ.get('MUSIC_KBPS', '96')

def main():
    cfg = loop.DRAFTS[CHOSEN]
    tmp = os.path.join(loop.HERE, '_work'); os.makedirs(tmp, exist_ok=True)
    L = 24 * 240 / cfg['bpm']
    raw = os.path.join(tmp, 'raw.wav'); loop.render(loop.build(CHOSEN, cfg, 3), raw)
    one = os.path.join(tmp, 'loop.wav')
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-ss', f'{L:.5f}', '-t', f'{L:.5f}', '-i', raw, '-af', 'volume=0.62,alimiter=limit=0.9', one], check=True)
    mp3 = os.path.join(tmp, 'loop.mp3')
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', one, '-codec:a', 'libmp3lame', '-b:a', BITRATE + 'k', '-joint_stereo', '1', mp3], check=True)
    fw = os.path.join(tmp, 'fan.wav'); loop.render(loop.fanfare(cfg), fw)
    fm = os.path.join(tmp, 'fan.mp3')
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', fw, '-t', '2.2', '-af', 'volume=0.62,afade=t=out:st=1.7:d=0.5,alimiter=limit=0.9', '-codec:a', 'libmp3lame', '-b:a', '96k', fm], check=True)
    b64 = lambda p: base64.b64encode(open(p, 'rb').read()).decode()
    out = os.path.join(ROOT, 'src', 'shared', 'music-data.js')
    with open(out, 'w') as f:
        f.write("'use strict';\n/* Generated by tools/music/make-assets.py (original music; see LICENSES.md). Do not edit by hand. */\n")
        f.write("CGB.MUSIC_DATA = { loopSeconds: %.4f, loop: '%s', fanfare: '%s' };\n" % (L, b64(mp3), b64(fm)))
    print('loop %.2f s, %d KB mp3; fanfare %d KB; wrote %s (%d KB)' % (L, os.path.getsize(mp3) // 1024, os.path.getsize(fm) // 1024, out, os.path.getsize(out) // 1024))
    shutil.rmtree(tmp)

if __name__ == '__main__':
    main()
